#!/usr/bin/env python3
"""Builds probe_shaders.h for the SA-nx resolve probe: every resolve variant as SPIR-V (for NVK,
through glslc) and as DKSH (for deko3d, through uam), from the same GLSL.

  gen_shaders.py RENDER_SHADERS PROBE_SHADERS GLSLC UAM OUT.h [--no-dksh]

The deko3d copies differ only where the two APIs do: no push constants (a uniform block at
binding 0 instead), no descriptor sets (storage buffers 0-2, textures 0-1), no specialisation
constants, gl_VertexID for gl_VertexIndex. Includes are expanded here because uam has none.
"""
import os, re, subprocess, sys, tempfile

render_dir, probe_dir, glslc, uam, out = sys.argv[1:6]
want_dksh = '--no-dksh' not in sys.argv

# name, source, kMax (None: as written)
VARIANTS = [
    ('test12', os.path.join(render_dir, 'oit_resolve.frag'), None),
    ('test12_lean', os.path.join(render_dir, 'oit_resolve.frag'), 8),
    ('test11', os.path.join(probe_dir, 'resolve_test11.frag'), None),
    ('test10', os.path.join(probe_dir, 'resolve_test10.frag'), None),
    ('walk', os.path.join(probe_dir, 'resolve_walk.frag'), None),
    ('head', os.path.join(probe_dir, 'resolve_head.frag'), None),
]

def expand(path):
    text = open(path).read()
    def inc(m):
        return expand(os.path.join(render_dir, m.group(1)))
    text = re.sub(r'^#include "([^"]+)"\s*$', inc, text, flags=re.M)
    return text

def with_kmax(text, kmax):
    if kmax is None:
        return text
    new, n = re.subn(r'layout\(constant_id = 0\) const int kMax = \d+;',
                     'layout(constant_id = 0) const int kMax = %d;' % kmax, text)
    assert n == 1, 'no kMax to change'
    return new

def for_deko(text):
    subs = [
        (r'#version 450', '#version 460'),
        (r'#extension GL_GOOGLE_include_directive : require\n', ''),
        (r'layout\(push_constant\) uniform Push', 'layout(std140, binding = 0) uniform Push'),
        (r'layout\(set = 1, binding = 0\) buffer Counter', 'layout(std430, binding = 0) buffer Counter'),
        (r'layout\(set = 1, binding = 1\) buffer Heads', 'layout(std430, binding = 1) buffer Heads'),
        (r'layout\(set = 1, binding = 2\) buffer Nodes', 'layout(std430, binding = 2) buffer Nodes'),
        (r'layout\(set = 1, binding = 3\) uniform sampler2D', 'layout(binding = 0) uniform sampler2D'),
        (r'layout\(set = 1, binding = 4\) uniform sampler2D', 'layout(binding = 1) uniform sampler2D'),
        (r'layout\(constant_id = 0\) const int', 'const int'),
        (r'gl_VertexIndex', 'gl_VertexID'),
    ]
    for a, b in subs:
        text = re.sub(a, b, text)
    assert 'set = ' not in text and 'push_constant' not in text, 'unconverted Vulkan layout'
    return text

def run(cmd):
    r = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('failed: %s\n%s%s' % (' '.join(cmd), r.stdout, r.stderr))

tmp = tempfile.mkdtemp()
def build(name, text, stage):
    src = os.path.join(tmp, name + '.' + stage)
    open(src, 'w').write(text)
    spv = os.path.join(tmp, name + '.spv')
    run([glslc, '--target-env=vulkan1.1', '-O', '-fshader-stage=' + stage, '-o', spv, src])
    words = open(spv, 'rb').read()
    dksh = b''
    if want_dksh:
        dsrc = os.path.join(tmp, name + '_dk.glsl')
        open(dsrc, 'w').write(for_deko(text))
        dk = os.path.join(tmp, name + '.dksh')
        run([uam, '-s', stage, '-o', dk, dsrc])
        dksh = open(dk, 'rb').read()
    return words, dksh

entries = [('vs',) + build('vs', expand(os.path.join(render_dir, 'oit_resolve.vert')), 'vert')]
for name, path, kmax in VARIANTS:
    entries.append((name,) + build(name, with_kmax(expand(path), kmax), 'frag'))

def arr(data):
    return ','.join(str(b) for b in data)
with open(out, 'w') as f:
    f.write('// Generated by switch/probe/gen_shaders.py. Do not edit.\n#pragma once\n#include <cstdint>\n\n')
    f.write('struct ProbeShader { const char* name; const unsigned char* spv; unsigned spv_size; '
            'const unsigned char* dksh; unsigned dksh_size; };\n\n')
    for name, spv, dksh in entries:
        f.write('alignas(4) static const unsigned char probe_%s_spv[] = {%s};\n' % (name, arr(spv)))
        f.write('alignas(4) static const unsigned char probe_%s_dksh[] = {%s};\n' % (name, arr(dksh) if dksh else '0'))
    f.write('\nstatic const ProbeShader kProbeVertex = {"vs", probe_vs_spv, sizeof probe_vs_spv, '
            'probe_vs_dksh, %d};\n' % len(entries[0][2]))
    f.write('static const ProbeShader kProbeVariants[] = {\n')
    for name, spv, dksh in entries[1:]:
        f.write('    {"%s", probe_%s_spv, sizeof probe_%s_spv, probe_%s_dksh, %d},\n' % (name, name, name, name, len(dksh)))
    f.write('};\n')
print('wrote', out)
